/** 三档的中文名，用于注入标题（让人一眼看出当前是哪一档）。 */
export const KICK_LABEL = {
  strict: '严禁',
  normal: '常规',
  eager: '敢踢'
};

/**
 * 取当前配置对应的提示词正文。
 *
 * @param {string} style      'bold' | 'conservative'（认不出一律当 bold）
 * @param {string} kickStance 'strict' | 'normal' | 'eager'（认不出一律当 normal）
 *
 * 认不出的值回落到默认档，与 skill.json settings 的默认值保持一致 ——
 * 免得配置写错时行为静默变成另一套（默认值：动手风格=bold，踢人权=normal）。
 */
export function moderationPrompt(style, kickStance) {
  const body = String(style ?? '').trim() === 'conservative' ? CONSERVATIVE : BOLD;
  const stance = KICK_STANCE[String(kickStance ?? '').trim()] || KICK_STANCE.normal;
  return `${body}\n\n${stance}`;
}