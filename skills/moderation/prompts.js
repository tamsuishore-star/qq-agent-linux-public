//
// ── 两版的差别只在一件事上：它多敢主动动手 ──
// 安全边界（群主/管理员动不了、时长上限、踢人是否可用）完全不随风格变化 ——
// 那是代码层硬约束，不在提示词里，改风格动不了它。
//
// 两版共用的那部分（怎么动手、规矩）抽在 COMMON 里，避免两份文案各自漂移 ——
// 以前 music 技能的 cardMode 就是这么分流的，后来还是漂移了一次。

