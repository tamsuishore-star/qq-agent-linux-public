/**
 * 非硬拦的提示词：这些词出现**不一定**违规（"国庆"可能是放假日常），
 * 但值得让模型再确认一遍。发布时不拦，只在返回里提示。
 */
const NEUTRAL_HINTS = ['国庆', '亚运', '奥运', '两会', '发布会', '声明', '回应', '通报', '官方'];

/** 把文本规整一下，便于匹配（去空白、全角转半角不必要，中文直接匹配）。 */
function normalize(text) {
  return String(text ?? '').replace(/\s+/g, '');
}

/**
 * 检查一段文本。
 * @returns {{ok: boolean, hit: string|null, hints: string[]}}
 */
export function checkContent(text) {
  const t = normalize(text);
  if (!t) return { ok: false, hit: '内容为空', hints: [] };
  for (const w of BLOCKED) {
    if (t.includes(w)) return { ok: false, hit: w, hints: [] };
  }
  const hints = NEUTRAL_HINTS.filter((w) => t.includes(w));
  return { ok: true, hit: null, hints };
}

/**
 * 热榜条目也要过一道 —— 热搜标题里时政占比很高，
 * 必须在**挑话题阶段**就滤掉，不能等模型写完再拦。
 */
export function isSafeTopic(title) {
  return checkContent(title).ok;
}

/** 供设置页展示用：当前禁用词条数。 */
export function blockedWordCount() {
  return BLOCKED.length;
}

/**
 * 允许抓取的图片域名白名单。
 *
 * 为什么必须白名单而不是"随便给个 URL 就传"：
 * send_qzone_msg 的 images 会把 URL 抓下来**上传到你的空间**。如果放开任意 URL，
 * 等于开了一条"把任意外链内容搬进自己空间"的通道 —— 可能被抓到内网地址（SSRF）、
 * 可能是别人的私密图、也可能是带版权纠纷的图。所以只放行确认为表情包图床的域名。
 */
const ALLOWED_IMAGE_HOSTS = new Set([
  'img.aigengtu.com',
  'aigengtu.com'
]);

/** 只接受 http(s) 且主机在白名单内。 */
export function isAllowedImageUrl(url) {
  let u;
  try { u = new URL(String(url ?? '')); } catch { return false; }
  if (u.protocol !== 'https:' && u.protocol !== 'http:') return false;
  return ALLOWED_IMAGE_HOSTS.has(u.hostname.toLowerCase());
}

/**
 * 从文本里捞"疑似提到人/群聊"的痕迹 —— 防隐私泄露的最后一道兜底网。
 *
 * ⚠️ 这一层的定位要说清楚：**它只拦高置信信号，不追求全覆盖。**
 *
 * 为什么不做全：中文里「XX说」和「想说」「我说的是」在字面上无法可靠区分，
 * 想要高召回就必然大量误杀（实测：贪心版会把"我也想说说这个游戏"当成提及他人拦掉）。
 * 误杀的代价是模型被莫名拒绝后反复重试、甚至干脆放弃发空间，比漏一两条更糟。
 *
 * 所以真正的隐私防线是**提示词里那条硬规矩**（不许写群聊、不许提群友）+ 选题来源
 * 隔离（只喂网络热点，不喂群聊内容）。这里只负责拦住最明显的几种：
 *   · 明确的群聊词：群友 / 群里 / 群聊 / 我们群 …
 *   · 群体指代：大家都在说 / 大家都在聊 …
 *   · 姓名式表达：2 字以上 + 言说动词，且不在误报黑名单里
 */
const FALSE_POSITIVES = new Set([
  '想说', '要说', '能说', '会说', '该说', '敢说', '是说', '再说', '才说', '都说', '也说', '就说',
  '来说', '不说', '没说', '得说', '的说', '的是', '的说', '是说',
  '今天', '明天', '昨天', '现在', '刚才', '等下', '回头', '顺便', '简单', '老实',
  '总的', '总的来', '认真', '客观', '坦白', '实话', '说实话', '老实说'
]);

export function mentionsPersonOrChat(text) {
  const t = String(text ?? '');

  // 1) 明确的群聊词 —— 高置信，直接拦
  const chat = t.match(/(?:群友|群里|群聊|我们群|咱群|这个群|本群|群里人|群内)/);
  if (chat) return chat[0];

  // 2) 群体指代
  //    只收「说/聊/讨论」—— 这些才意味着**在引用别人的话**。
  //    「大家觉得/大家认为」是征求意见，不涉及隐私，收进来只会误杀。
  //    另注意 "都在" 是**两个**字：(?:都|全|在)? 匹配不了它（实测踩过），要显式列上。
  const crowd = t.match(/大家(?:都|全|都在|全在|在)?(?:说|聊|讨论)/);
  if (crowd) return crowd[0];

  // 3) 姓名式表达：名字 2~6 字（不含言说/人称/程度副词），后面接言说类动词
  const m = t.match(/([^\s说你我他她它想你要能会该敢都也就才再别很不没]{2,6})(?:说过|说|讲的|提到|问我|吐槽|发的)/);
  if (m && !FALSE_POSITIVES.has(m[1])) return m[0];

  return null;
}